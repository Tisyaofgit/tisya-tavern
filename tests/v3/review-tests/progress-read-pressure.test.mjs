import test from 'node:test';
import assert from 'node:assert/strict';
import {createCapabilities} from '../../../v3/capabilities.mjs';
import {createProgressService} from '../../../v3/progress.mjs';
const tick=()=>new Promise(resolve=>setImmediate(resolve));
test('stream character events do not repeatedly read books; phase changes coalesce and terminal state remains visible',async()=>{
 const progress=createProgressService();let reads=0,active=0,max=0,release=null;
 const caps=createCapabilities({progress,books:{binding:async()=>{reads++;active++;max=Math.max(max,active);if(release)await release.promise;active--;return null;}}}),events=[];
 caps.subscribe(s=>events.push(s));await tick();const initial=reads;
 let resolve;release={promise:new Promise(r=>resolve=r)};
 progress.runtime({requestKey:'r',phase:'model-a',status:'running',characters:0});
 for(let i=1;i<=1000;i++)progress.runtime({requestKey:'r',phase:'model-a',status:'running',characters:i});
 assert.equal(reads,initial+1);
 progress.runtime({requestKey:'r',phase:'writer',status:'running'});
 progress.runtime({requestKey:'r',phase:'complete',status:'saved'});
 release=null;resolve();await tick();await tick();
 assert.equal(reads,initial+2);assert.equal(max,1);
 assert.equal(events.at(-1).progress.status,'saved');assert.equal(events.at(-1).progress.phase,'complete');
 caps.dispose();progress.dispose();
});
