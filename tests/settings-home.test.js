import test from 'node:test';
import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
import {mountSettingsHome} from '../settings-home.js';
import {settingsDestinations} from '../settings-navigation.js';
test('settings categories stay on one layer and search reaches every unique destination',async()=>{
 const w=new Window(),d=w.document,box=d.createElement('div');d.body.append(box);
 const options={rows:settingsDestinations(),version:'test'};mountSettingsHome(box,options);
 assert.equal(box.querySelectorAll('details').length,0);
 assert.equal(box.querySelectorAll('[data-open-group]').length,6);
 const actions=[...box.querySelectorAll('[data-tisya-action]')].map(n=>n.dataset.tisyaAction);assert.equal(actions.length,new Set(actions).size);
 const input=box.querySelector('input');box.querySelector('[data-open-group="reading"]').click();
 assert.equal(box.querySelector('[data-settings-group="reading"]').hidden,false);assert.equal(box.querySelector('[data-settings-group="world"]').hidden,true);assert.equal(box.querySelector('.tisya-menu-grid').hidden,true);
 input.value='世界书';input.oninput();assert.equal(box.querySelector('[data-settings-group="world"]').hidden,false);assert.equal(box.querySelectorAll('.tisya-setting-destination:not([hidden])').length,1);
 input.value='用户身份';input.oninput();assert.equal(box.querySelector('[data-tisya-action="user-identity"]').hidden,false);assert.equal(box.querySelector('[data-tisya-action="assistant"]').hidden,true);
 input.value='不存在的功能';input.oninput();assert.match(box.querySelector('[role=status]').textContent,/没有找到/);
 input.value='';input.oninput();assert.equal(box.querySelector('[data-settings-group="reading"]').hidden,false);
 mountSettingsHome(box,{...options,identityName:'新角色'});assert.equal(box.querySelector('[data-settings-group="reading"]').hidden,false);
 box.querySelector('[aria-label="返回设置目录"]').click();assert.equal(box.querySelector('.tisya-menu-grid').hidden,false);assert.equal(box.querySelectorAll('[data-settings-group]:not([hidden])').length,0);await w.happyDOM.abort();
});
